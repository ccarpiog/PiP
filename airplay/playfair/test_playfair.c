static void print_hex(const char* label, const unsigned char* data, int len){
  printf("%s: ", label);
  for (int i = 0; i < len; i++) {
    printf("%02x ", data[i]);
    if ((i + 1) % 16 == 0) printf("\n");
  }
  if (len % 16 != 0) printf("\n");
}

static int test_decrypt(){
  printf("=== Test 1: Verify playfair_decrypt with captured data ===\n");
  unsigned char decrypted[16];
  playfair_decrypt((unsigned char*)message3, (unsigned char*)captured_ekey, decrypted);

  printf("Expected aeskey: ");
  print_hex("", expected_aeskey, 16);
  printf("Decrypted key:   ");
  print_hex("", decrypted, 16);

  if (memcmp(decrypted, expected_aeskey, 16) == 0) {
    printf("✓ Decryption test PASSED\n\n");
    return 0;
  } else {
    printf("✗ Decryption test FAILED\n\n");
    return 1;
  }
}

static int test_encrypt_decrypt_roundtrip(){
  printf("=== Test 2: Encrypt then decrypt roundtrip ===\n");
  unsigned char encrypted[72];
  unsigned char decrypted[16];

  // Encrypt the expected key
  playfair_encrypt((unsigned char*)message3, (unsigned char*)expected_aeskey, encrypted);

  printf("Encrypted ekey: ");
  print_hex("", encrypted, 72);

  // Decrypt it back
  playfair_decrypt((unsigned char*)message3, encrypted, decrypted);

  printf("Decrypted key:  ");
  print_hex("", decrypted, 16);

  if (memcmp(decrypted, expected_aeskey, 16) == 0) {
    printf("✓ Roundtrip test PASSED\n\n");
    return 0;
  } else {
    printf("✗ Roundtrip test FAILED\n\n");
    return 1;
  }
}

